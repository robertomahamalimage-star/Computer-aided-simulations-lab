def run_replications(label: str, n_rep: int = 5, **kwargs) -> pd.DataFrame:
    """Run independent replications and return one KPI row per replication."""
    if isinstance(n_rep, bool) or not isinstance(n_rep, (int, np.integer)) or n_rep <= 0:
        raise ValueError("n_rep must be a positive integer")
    rows = []
    for rep in range(n_rep):
        sim = TaxiSimulation(seed=1000 + rep, **kwargs)
        row = sim.run()
        row["scenario"] = label
        row["replication"] = rep
        rows.append(row)
    return pd.DataFrame(rows)


def scenario_experiments(n_rep: int = 5) -> pd.DataFrame:
    """Scenarios designed to expose both demand and supply-side effects.

    Heavy-rain demand-only is an intentionally artificial control scenario: it
    increases demand exactly like heavy rain but disables the speed penalty. By
    comparing it with Heavy rain (full feedback), one can isolate the extra
    queueing caused by slower taxi circulation.
    """
    common = dict(
        duration_hours=24,
        fleet_size=40,
        p_app=0.70,
        day_of_week="Wednesday",
        include_hubs=True,
        rebalancing=True,
    )

    frames = [
        run_replications("Baseline + hubs", n_rep, **common),
        run_replications(
            "No station/airport bursts", n_rep, include_hubs=False,
            duration_hours=24, fleet_size=40, p_app=0.70,
            day_of_week="Wednesday", rebalancing=True,
        ),
        run_replications(
            "Heavy rain - demand only", n_rep,
            weather_intensity=1.0, weather_speed_penalty=0.0, **common,
        ),
        run_replications(
            "Heavy rain - demand + slower taxis", n_rep,
            weather_intensity=1.0, weather_speed_penalty=0.30, **common,
        ),
        run_replications(
            "Public transport strike", n_rep,
            strike=True, **common,
        ),
        run_replications(
            "Phased large evening event", n_rep,
            event_zone="NE", event_start_hour=20.0, event_end_hour=22.0,
            event_attendance=1100, event_inbound_taxi_share=0.07,
            event_outbound_taxi_share=0.11, event_multiplier=1.0,
            event_speed_factor=0.60, **common,
        ),
        run_replications(
            "Combined stress", n_rep,
            day_of_week="Friday", weather_intensity=1.0, strike=True,
            event_zone="NE", event_start_hour=20.0, event_end_hour=22.0,
            event_attendance=1100, event_inbound_taxi_share=0.07,
            event_outbound_taxi_share=0.11, event_multiplier=1.0,
            event_speed_factor=0.60,
            duration_hours=24, fleet_size=40, p_app=0.70,
            include_hubs=True, rebalancing=True,
        ),
    ]
    return pd.concat(frames, ignore_index=True)


def summarize_experiments(df: pd.DataFrame) -> pd.DataFrame:
    """Report means, replication counts and between-replication variability.

    Scenarios receive equal weight per replication. Standard deviations are
    sample standard deviations, not confidence intervals; with one replication
    they are undefined (NaN).
    """
    cols = [
        "generated",
        "station_generated",
        "airport_generated",
        "event_generated",
        "completion_rate",
        "avg_app_wait_min",
        "avg_app_wait_lower_bound_min",
        "avg_stand_walk_min",
        "avg_stand_wait_min",
        "avg_total_access_min",
        "not_boarded_app",
        "not_boarded_stand",
        "onboard",
        "availability_idle_share",
        "utilization_occupied_share",
        "empty_distance_share",
    ]
    grouped = df.groupby("scenario", sort=False)
    summary = grouped[cols].mean()
    summary.insert(0, "replications", grouped.size())
    for col in ("completion_rate", "avg_app_wait_min", "avg_stand_wait_min"):
        summary[f"{col}_std"] = grouped[col].std(ddof=1)
    return summary.round(3)


def basic_sanity_checks() -> None:
    """Fast invariants that catch common implementation errors.

    These are not a complete statistical validation. They verify that hub demand
    is actually generated, passenger counters reconcile, probabilities/shares
    remain in range, and fleet state-time accounting covers the whole horizon.
    """
    sim = TaxiSimulation(duration_hours=24, fleet_size=30, seed=2026, include_hubs=True)
    metrics = sim.run()

    assert metrics["station_generated"] > 0, "Station demand was not generated"
    assert metrics["airport_generated"] > 0, "Airport demand was not generated"
    assert (
        metrics["urban_generated"]
        + metrics["station_generated"]
        + metrics["airport_generated"]
        + metrics["event_inbound_generated"]
        + metrics["event_outbound_generated"]
        == metrics["generated"]
    ), "Passenger source counters do not reconcile"
    assert 0.0 <= metrics["completion_rate"] <= 1.0
    assert 0.0 <= metrics["availability_idle_share"] <= 1.0
    assert 0.0 <= metrics["utilization_occupied_share"] <= 1.0
    assert 0.0 <= metrics["empty_running_share"] <= 1.0
    assert metrics["completed"] + metrics["unfinished_app"] + metrics["unfinished_stand"] == metrics["generated"]
    assert metrics["completed"] + metrics["onboard"] == metrics["boarded"]
    assert metrics["boarded"] + metrics["not_boarded_app"] + metrics["not_boarded_stand"] == metrics["generated"]
    for p in sim.passengers.values():
        if p.assignment_time is not None:
            assert p.request_time <= p.assignment_time <= sim.current_time
        if p.pickup_time is not None:
            assert p.request_time <= p.pickup_time <= sim.current_time
            if p.assignment_time is not None:
                assert p.assignment_time <= p.pickup_time
            if p.stand_arrival_time is not None:
                assert p.stand_arrival_time <= p.pickup_time
        if p.dropoff_time is not None:
            assert p.pickup_time <= p.dropoff_time <= sim.current_time

    event_sim = TaxiSimulation(
        duration_hours=24, fleet_size=30, seed=2027, include_hubs=False,
        event_zone="NE", event_start_hour=20.0, event_end_hour=22.0,
        event_attendance=1000, event_inbound_taxi_share=0.08,
        event_outbound_taxi_share=0.12,
    )
    event_metrics = event_sim.run()
    assert event_metrics["event_inbound_generated"] > 0, "No pre-event flow generated"
    assert event_metrics["event_outbound_generated"] > 0, "No post-event flow generated"

    # Each taxi is in exactly one state at the beginning of each time step.
    total_share = (
        metrics["availability_idle_share"]
        + metrics["utilization_occupied_share"]
        + metrics["empty_running_share"]
    )
    assert abs(total_share - 1.0) < 1e-9, "Fleet time shares do not sum to one"


if __name__ == "__main__":
    basic_sanity_checks()
    print("Sanity checks passed.\n")

    n_rep = 5
    results = scenario_experiments(n_rep=n_rep)
    summary = summarize_experiments(results)

    print(f"Mean KPIs over {n_rep} independent replications\n")
    print("Waiting/access means include everyone who boarded, even if still onboard.")
    print("Walking means include everyone who reached a stand.")
    print("Lower bounds include time already spent by customers still waiting.")
    print("Backlogs and sample standard deviations are reported separately.\n")
    print(summary.to_string())

    results.to_csv("taxi_simulation_v3_results.csv", index=False)
    summary.to_csv("taxi_simulation_v3_summary.csv")
