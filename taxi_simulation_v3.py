"""Extended taxi-system simulator for a mobility laboratory.

The model is intentionally detailed enough to reproduce the main feedback loops
of an urban taxi system, while remaining small enough to explain in a report.

Main mechanisms
---------------
* non-stationary, zone-dependent urban demand;
* explicit day-of-week effects;
* app/phone requests and walk-to-stand passengers;
* railway-station and airport demand bursts from scheduled arrivals;
* some ordinary city trips whose destination is a station/airport;
* closest-idle-taxi dispatching;
* finite-capacity taxi stands;
* dynamic taxi speeds that react to time of day, weather, public-transport
  disruptions, phased events and short-lived congestion around transport hubs;
* phased event mobility: inbound flow before the event, low event-generated
  demand during it, and a concentrated/decreasing outbound burst afterwards;
* empty return to stands and optional demand-based fleet rebalancing;
* Monte-Carlo scenario experiments and basic sanity tests.

Important modelling idea
------------------------
Several exogenous factors affect BOTH demand and effective supply. For example,
heavy rain increases the taxi-request rate but also lowers vehicle speed. Slower
trips keep taxis occupied (or travelling empty) for longer, which reduces the
number of taxis that are immediately available and may create a queueing
feedback loop.

Units
-----
Distance: km
Time: minutes internally; passenger arrival rates are passengers/hour
Speed: km/hour

All default numerical values are illustrative and should be calibrated if real
city data are available.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Dict, List, Optional, Tuple
import math
import numpy as np
import pandas as pd


# ---------------------------------------------------------------------------
# Data structures
# ---------------------------------------------------------------------------


@dataclass
class Zone:
    """Rectangular demand zone."""

    name: str
    xmin: float
    xmax: float
    ymin: float
    ymax: float
    base_rate_per_hour: float

    def sample_point(self, rng: np.random.Generator) -> np.ndarray:
        """Draw a uniformly distributed point inside the zone."""
        return np.array(
            [rng.uniform(self.xmin, self.xmax), rng.uniform(self.ymin, self.ymax)],
            dtype=float,
        )

    def contains(self, pos: np.ndarray) -> bool:
        """Return True when *pos* belongs to this rectangular zone."""
        return self.xmin <= pos[0] <= self.xmax and self.ymin <= pos[1] <= self.ymax


@dataclass
class Stand:
    """Taxi stand with finite parking capacity and a passenger queue."""

    sid: int
    pos: np.ndarray
    capacity: int
    zone_name: str
    name: str = ""
    passenger_queue: List[int] = field(default_factory=list)


@dataclass
class TransportHub:
    """Railway station or airport that generates scheduled demand bursts.

    arrival_hours contains clock times (0-24) at which a train/flight arrival
    creates a burst of arriving travellers. The number requesting a taxi is
    generated in two stages:

        travellers ~ Poisson(mean_arriving_travellers)
        taxi_users  ~ Binomial(travellers, taxi_share)

    This preserves the bursty character of real terminal demand instead of
    spreading those requests uniformly across the surrounding zone.
    """

    hid: int
    name: str
    kind: str  # "station" or "airport"
    pos: np.ndarray
    zone_name: str
    stand_id: int
    arrival_hours: Tuple[float, ...]
    mean_arriving_travellers: float
    taxi_share: float
    p_app: float
    destination_probs: Dict[str, float]


@dataclass
class TransitDisruption:
    """Temporary reduction in public-transport availability.

    availability is between 0 and 1:
      1.0 = normal service
      0.0 = no usable service

    zone_name=None means that the disruption is city-wide.
    """

    label: str
    start_hour: float
    end_hour: float
    availability: float
    zone_name: Optional[str] = None


@dataclass
class Passenger:
    """Passenger generated by ordinary city demand or by a transport hub."""

    pid: int
    origin: np.ndarray
    destination: np.ndarray
    origin_zone: str
    destination_zone: str
    mode: str  # "app" or "stand"
    request_time: float
    source_type: str = "urban"  # urban, station, airport, event_inbound, event_outbound
    source_name: Optional[str] = None

    status: str = "new"
    stand_id: Optional[int] = None
    walk_remaining: float = 0.0
    stand_arrival_time: Optional[float] = None
    assigned_taxi: Optional[int] = None
    assignment_time: Optional[float] = None
    pickup_time: Optional[float] = None
    dropoff_time: Optional[float] = None


@dataclass
class Taxi:
    """Taxi agent.

    States
    ------
    idle          parked at a stand and dispatchable
    to_pickup     driving empty to an app/phone passenger
    occupied      carrying a passenger
    returning     empty and driving back to a stand
    rebalancing   empty and intentionally relocating to another stand

    Unlike the first version of the simulator, movement is distance-based.
    At every time step, the taxi moves according to the CURRENT effective
    speed. Therefore a condition that changes during a trip can immediately
    lengthen the trip.
    """

    tid: int
    pos: np.ndarray
    state: str = "idle"
    stand_id: Optional[int] = None
    passenger_id: Optional[int] = None
    target_pos: Optional[np.ndarray] = None
    target_stand_id: Optional[int] = None

    occupied_minutes: float = 0.0
    idle_minutes: float = 0.0
    pickup_minutes: float = 0.0
    return_minutes: float = 0.0
    rebalance_minutes: float = 0.0

    occupied_km: float = 0.0
    pickup_km: float = 0.0
    return_km: float = 0.0
    rebalance_km: float = 0.0


# ---------------------------------------------------------------------------
# Simulator
# ---------------------------------------------------------------------------


class TaxiSimulation:
    """Discrete-time taxi simulator with dynamic demand and dynamic supply."""

    VALID_DAYS = (
        "Monday", "Tuesday", "Wednesday", "Thursday", "Friday", "Saturday", "Sunday"
    )

    def __init__(
        self,
        fleet_size: int = 40,
        duration_hours: float = 24.0,
        dt_minutes: float = 1.0,
        p_app: float = 0.70,
        taxi_speed_kmh: float = 28.0,
        walking_speed_kmh: float = 4.8,
        road_distance_factor: float = 1.20,
        demand_multiplier: float = 1.0,
        day_of_week: str = "Wednesday",
        weekend: Optional[bool] = None,  # backwards-compatible shortcut
        # Weather: 0=no rain, 1=heavy rain. Values in between are allowed.
        weather_intensity: float = 0.0,
        rain: bool = False,  # backwards-compatible shortcut -> moderate rain
        weather_demand_sensitivity: float = 0.35,
        weather_speed_penalty: float = 0.30,
        # Public transport: 1=normal, 0=unavailable.
        public_transport_availability: float = 1.0,
        strike: bool = False,
        transit_disruptions: Optional[List[TransitDisruption]] = None,
        pt_demand_sensitivity: float = 1.0,
        pt_road_congestion_sensitivity: float = 0.18,
        # Event model.  event_start_hour/end_hour describe the actual event.
        # Taxi demand is generated in three phases rather than as one flat shock:
        #   1) inbound flow during event_pre_window_min before the event;
        #   2) no extra event-generated trips during the event itself;
        #   3) concentrated outbound flow during event_post_window_min after it.
        # event_multiplier is retained for backwards compatibility and scales the
        # event-generated taxi volume (1.0 = volumes implied by attendance/shares).
        event_zone: Optional[str] = None,
        event_start_hour: float = 20.0,
        event_end_hour: float = 22.0,
        event_multiplier: float = 1.0,
        event_attendance: float = 900.0,
        event_inbound_taxi_share: float = 0.07,
        event_outbound_taxi_share: float = 0.10,
        event_pre_window_min: float = 120.0,
        event_post_window_min: float = 90.0,
        event_post_decay_tau_min: float = 28.0,
        event_during_local_demand_factor: float = 0.70,
        event_pre_speed_factor: float = 0.82,
        event_during_speed_factor: float = 0.88,
        event_speed_factor: float = 0.60,  # strongest post-event slowdown
        event_position: Optional[Tuple[float, float]] = None,
        # Railway station / airport mechanisms.
        include_hubs: bool = True,
        urban_to_hub_probability: float = 0.04,
        hub_congestion_window_min: float = 20.0,
        hub_congestion_radius_km: float = 1.0,
        hub_congestion_speed_factor: float = 0.85,
        # Fleet management.
        rebalancing: bool = True,
        rebalance_interval_min: int = 30,
        rebalance_fraction: float = 0.25,
        seed: int = 1,
    ) -> None:
        # Reject invalid inputs before they can create negative arrival rates,
        # divisions by zero, or a simulation whose clock never advances.
        if isinstance(fleet_size, bool) or not isinstance(fleet_size, (int, np.integer)) or fleet_size < 0:
            raise ValueError("fleet_size must be a non-negative integer")
        for name, value in {
            "duration_hours": duration_hours,
            "dt_minutes": dt_minutes,
            "taxi_speed_kmh": taxi_speed_kmh,
            "walking_speed_kmh": walking_speed_kmh,
            "road_distance_factor": road_distance_factor,
            "rebalance_interval_min": rebalance_interval_min,
            "event_pre_window_min": event_pre_window_min,
            "event_post_window_min": event_post_window_min,
            "event_post_decay_tau_min": event_post_decay_tau_min,
        }.items():
            if not math.isfinite(value) or value <= 0:
                raise ValueError(f"{name} must be finite and positive")
        for name, value in {
            "p_app": p_app,
            "weather_intensity": weather_intensity,
            "weather_speed_penalty": weather_speed_penalty,
            "public_transport_availability": public_transport_availability,
            "event_inbound_taxi_share": event_inbound_taxi_share,
            "event_outbound_taxi_share": event_outbound_taxi_share,
            "urban_to_hub_probability": urban_to_hub_probability,
            "rebalance_fraction": rebalance_fraction,
        }.items():
            if not 0.0 <= value <= 1.0:
                raise ValueError(f"{name} must be in [0, 1]")
        for name, value in {
            "demand_multiplier": demand_multiplier,
            "weather_demand_sensitivity": weather_demand_sensitivity,
            "pt_demand_sensitivity": pt_demand_sensitivity,
            "pt_road_congestion_sensitivity": pt_road_congestion_sensitivity,
            "event_attendance": event_attendance,
            "event_multiplier": event_multiplier,
            "event_during_local_demand_factor": event_during_local_demand_factor,
            "hub_congestion_window_min": hub_congestion_window_min,
            "hub_congestion_radius_km": hub_congestion_radius_km,
        }.items():
            if not math.isfinite(value) or value < 0:
                raise ValueError(f"{name} must be finite and non-negative")
        if day_of_week not in self.VALID_DAYS:
            raise ValueError(f"day_of_week must be one of {self.VALID_DAYS}")
        if weekend is True:
            day_of_week = "Saturday"
        if rain and weather_intensity == 0.0:
            weather_intensity = 0.60

        self.fleet_size = fleet_size
        self.duration_minutes = duration_hours * 60.0
        self.dt = dt_minutes
        self.p_app = p_app
        self.taxi_speed_kmh = taxi_speed_kmh
        self.walking_speed_kmh = walking_speed_kmh
        self.road_distance_factor = road_distance_factor
        self.demand_multiplier = demand_multiplier
        self.day_of_week = day_of_week

        self.weather_intensity = weather_intensity
        self.weather_demand_sensitivity = weather_demand_sensitivity
        self.weather_speed_penalty = weather_speed_penalty

        self.public_transport_availability = public_transport_availability
        self.strike = strike
        self.transit_disruptions = transit_disruptions or []
        self.pt_demand_sensitivity = pt_demand_sensitivity
        self.pt_road_congestion_sensitivity = pt_road_congestion_sensitivity

        self.event_zone = event_zone
        self.event_start_hour = event_start_hour
        self.event_end_hour = event_end_hour
        self.event_multiplier = event_multiplier
        self.event_attendance = event_attendance
        self.event_inbound_taxi_share = event_inbound_taxi_share
        self.event_outbound_taxi_share = event_outbound_taxi_share
        self.event_pre_window_min = event_pre_window_min
        self.event_post_window_min = event_post_window_min
        self.event_post_decay_tau_min = event_post_decay_tau_min
        self.event_during_local_demand_factor = event_during_local_demand_factor
        self.event_pre_speed_factor = event_pre_speed_factor
        self.event_during_speed_factor = event_during_speed_factor
        self.event_speed_factor = event_speed_factor
        self.event_position = (
            np.array(event_position, dtype=float) if event_position is not None else None
        )

        self.include_hubs = include_hubs
        self.urban_to_hub_probability = urban_to_hub_probability
        self.hub_congestion_window_min = hub_congestion_window_min
        self.hub_congestion_radius_km = hub_congestion_radius_km
        self.hub_congestion_speed_factor = hub_congestion_speed_factor

        self.rebalancing = rebalancing
        self.rebalance_interval_min = rebalance_interval_min
        self.rebalance_fraction = rebalance_fraction
        self.rng = np.random.default_rng(seed)

        self.zones = self._make_default_zones()
        self.zone_by_name = {z.name: z for z in self.zones}
        if self.event_zone is not None and self.event_zone not in self.zone_by_name:
            raise ValueError(f"Unknown event_zone: {self.event_zone}")
        if self.event_zone is not None and self.event_position is None:
            ez = self.zone_by_name[self.event_zone]
            self.event_position = np.array(
                [(ez.xmin + ez.xmax) / 2.0, (ez.ymin + ez.ymax) / 2.0], dtype=float
            )
        self.stands = self._make_default_stands()
        self.hubs = self._make_default_hubs() if include_hubs else {}
        if self.include_hubs:
            self._add_hub_stands()
        self.taxis = self._make_taxis()

        self.passengers: Dict[int, Passenger] = {}
        self.app_queue: List[int] = []
        self.next_pid = 0
        self.current_time = 0.0

        # Hub arrivals already processed and temporary terminal congestion.
        self.processed_hub_arrivals: set[Tuple[int, int, int]] = set()
        self.hub_congestion_until: Dict[int, float] = {hid: -math.inf for hid in self.hubs}

        # Counters used for performance indicators.
        self.total_generated = 0
        self.urban_generated = 0
        self.station_generated = 0
        self.airport_generated = 0
        self.event_inbound_generated = 0
        self.event_outbound_generated = 0
        self.app_generated = 0
        self.stand_generated = 0
        self.immediate_app_dispatches = 0

    # -------------------------- geometry and defaults ---------------------

    @staticmethod
    def _make_default_zones() -> List[Zone]:
        """Create a 10 km x 10 km toy city split into four zones."""
        return [
            Zone("NW", 0, 5, 5, 10, 5.0),
            Zone("NE", 5, 10, 5, 10, 6.0),
            Zone("SW", 0, 5, 0, 5, 4.0),
            Zone("SE", 5, 10, 0, 5, 5.0),
        ]

    @staticmethod
    def _make_default_stands() -> Dict[int, Stand]:
        """Two ordinary taxi stands per zone."""
        raw = [
            (0, (1.3, 8.0), "NW"),
            (1, (3.8, 6.2), "NW"),
            (2, (6.2, 8.3), "NE"),
            (3, (8.5, 6.3), "NE"),
            (4, (1.5, 2.0), "SW"),
            (5, (3.8, 3.8), "SW"),
            (6, (6.2, 3.6), "SE"),
            (7, (8.6, 1.8), "SE"),
        ]
        return {
            sid: Stand(
                sid=sid,
                pos=np.array(pos, dtype=float),
                capacity=10,
                zone_name=zone,
                name=f"Stand {sid}",
            )
            for sid, pos, zone in raw
        }

    @staticmethod
    def _make_default_hubs() -> Dict[int, TransportHub]:
        """Illustrative central station and airport.

        Arrival schedules are deliberately sparse so that the bursts are easy
        to observe in experiments. They are NOT intended to reproduce any real
        city's timetable.
        """
        station = TransportHub(
            hid=0,
            name="Central Station",
            kind="station",
            pos=np.array([5.2, 7.5], dtype=float),
            zone_name="NE",
            stand_id=8,
            arrival_hours=(6.50, 7.00, 7.50, 8.00, 8.50, 9.00, 12.00,
                           17.00, 17.50, 18.00, 18.50, 21.00, 23.00),
            mean_arriving_travellers=70.0,
            taxi_share=0.08,
            p_app=0.45,
            destination_probs={"NW": 0.30, "NE": 0.25, "SW": 0.20, "SE": 0.25},
        )
        airport = TransportHub(
            hid=1,
            name="Airport",
            kind="airport",
            pos=np.array([9.3, 9.2], dtype=float),
            zone_name="NE",
            stand_id=9,
            arrival_hours=(7.25, 8.75, 10.50, 12.00, 14.50, 16.50, 18.75, 21.00, 23.00),
            mean_arriving_travellers=55.0,
            taxi_share=0.16,
            p_app=0.60,
            destination_probs={"NW": 0.25, "NE": 0.30, "SW": 0.20, "SE": 0.25},
        )
        return {station.hid: station, airport.hid: airport}

    def _add_hub_stands(self) -> None:
        """Add dedicated terminal taxi stands at station and airport."""
        for hub in self.hubs.values():
            capacity = 14 if hub.kind == "station" else 18
            self.stands[hub.stand_id] = Stand(
                sid=hub.stand_id,
                pos=hub.pos.copy(),
                capacity=capacity,
                zone_name=hub.zone_name,
                name=f"{hub.name} taxi stand",
            )

    def _make_taxis(self) -> Dict[int, Taxi]:
        """Distribute the fleet round-robin without exceeding stand capacities.

        This model starts every taxi parked. A fleet larger than all available
        parking spaces therefore needs a different initial-state model.
        """
        taxis: Dict[int, Taxi] = {}
        slots = [
            sid
            for level in range(max(s.capacity for s in self.stands.values()))
            for sid, stand in self.stands.items()
            if level < stand.capacity
        ]
        if self.fleet_size > len(slots):
            raise ValueError(
                f"fleet_size ({self.fleet_size}) exceeds total stand capacity ({len(slots)})"
            )
        for tid, sid in enumerate(slots[:self.fleet_size]):
            taxis[tid] = Taxi(
                tid=tid,
                pos=self.stands[sid].pos.copy(),
                state="idle",
                stand_id=sid,
            )
        return taxis

    def distance_km(self, a: np.ndarray, b: np.ndarray) -> float:
        """Approximate network distance as Euclidean distance times a detour factor."""
        return float(np.linalg.norm(a - b) * self.road_distance_factor)

    def zone_name_at(self, pos: np.ndarray) -> str:
        """Return the zone containing *pos*; use nearest zone centre as fallback."""
        for zone in self.zones:
            if zone.contains(pos):
                return zone.name
        centres = {
            z.name: np.array([(z.xmin + z.xmax) / 2, (z.ymin + z.ymax) / 2])
            for z in self.zones
        }
        return min(centres, key=lambda name: float(np.linalg.norm(pos - centres[name])))

    # ------------------------------ time helpers -------------------------

    @property
    def step_duration(self) -> float:
        """Minutes in the next interval, shortened at the observation horizon.

        Keep the requested resolution in self.dt. Demand, walking, driving and
        fleet-time accounting must all use the same actual interval length.
        """
        return max(0.0, min(self.dt, self.duration_minutes - self.current_time))

    @staticmethod
    def _hour_in_window(hour: float, start_hour: float, end_hour: float) -> bool:
        """Clock-window test that also supports intervals crossing midnight."""
        if start_hour <= end_hour:
            return start_hour <= hour < end_hour
        return hour >= start_hour or hour < end_hour

    def clock_hour(self, minute: float) -> float:
        return (minute / 60.0) % 24.0

    def day_name_at(self, minute: float) -> str:
        """Day of week, allowing simulations longer than 24 hours."""
        start_idx = self.VALID_DAYS.index(self.day_of_week)
        day_offset = int(minute // (24.0 * 60.0))
        return self.VALID_DAYS[(start_idx + day_offset) % 7]

    def event_phase(self, minute: float) -> Tuple[str, float]:
        """Return the event phase and normalized progress within that phase.

        Phases are ``pre``, ``during``, ``post`` and ``none``.  Clock arithmetic
        is circular, so the logic also works when an event or its post-event
        dispersal crosses midnight.  Progress is in [0, 1].
        """
        if self.event_zone is None:
            return "none", 0.0

        clock_min = minute % 1440.0
        start = (self.event_start_hour * 60.0) % 1440.0
        end = (self.event_end_hour * 60.0) % 1440.0
        duration = (end - start) % 1440.0
        if duration <= 1e-9:
            duration = 1440.0

        since_start = (clock_min - start) % 1440.0
        if since_start < duration:
            return "during", min(1.0, since_start / duration)

        until_start = (start - clock_min) % 1440.0
        if 0.0 < until_start <= self.event_pre_window_min:
            progress = 1.0 - until_start / self.event_pre_window_min
            return "pre", float(np.clip(progress, 0.0, 1.0))

        since_end = (clock_min - end) % 1440.0
        if 0.0 <= since_end < self.event_post_window_min:
            progress = since_end / self.event_post_window_min
            return "post", float(np.clip(progress, 0.0, 1.0))

        return "none", 0.0

    def event_active(self, minute: float) -> bool:
        """Backwards-compatible indicator: True in any event-related phase."""
        return self.event_phase(minute)[0] != "none"

    def event_inbound_rate_per_minute(self, minute: float) -> float:
        """Expected inbound event taxi passengers per minute.

        A triangular ramp puts relatively more arrivals close to event start.
        The profile integrates approximately to
        attendance * inbound_taxi_share * event_multiplier over the pre-window.
        """
        phase, progress = self.event_phase(minute)
        if phase != "pre":
            return 0.0
        total = (
            self.event_attendance
            * self.event_inbound_taxi_share
            * self.event_multiplier
        )
        return total * (2.0 * progress) / self.event_pre_window_min

    def event_outbound_rate_per_minute(self, minute: float) -> float:
        """Expected post-event taxi passengers per minute.

        Outbound demand is highest immediately after the event and then decays
        exponentially.  The normalization makes the finite post-event window
        integrate to the requested total taxi share.
        """
        phase, progress = self.event_phase(minute)
        if phase != "post":
            return 0.0
        elapsed = progress * self.event_post_window_min
        tau = self.event_post_decay_tau_min
        norm = tau * (1.0 - math.exp(-self.event_post_window_min / tau))
        total = (
            self.event_attendance
            * self.event_outbound_taxi_share
            * self.event_multiplier
        )
        return total * math.exp(-elapsed / tau) / norm

    # ----------------------- demand AND supply shocks --------------------

    def public_transport_availability_at(self, minute: float, zone_name: str) -> float:
        """Effective transit availability after strikes and local disruptions."""
        hour = self.clock_hour(minute)
        availability = self.public_transport_availability

        # Backwards-compatible strike switch: strong city-wide service reduction.
        if self.strike and 6.0 <= hour < 22.0:
            availability = min(availability, 0.25)

        # Multiple disruptions can overlap; the most restrictive one dominates.
        for disruption in self.transit_disruptions:
            if disruption.zone_name not in (None, zone_name):
                continue
            if self._hour_in_window(hour, disruption.start_hour, disruption.end_hour):
                availability = min(availability, disruption.availability)

        return float(np.clip(availability, 0.0, 1.0))

    def base_traffic_speed(self, minute: float) -> float:
        """Traffic speed before exogenous shock multipliers are applied."""
        hour = self.clock_hour(minute)
        if 7.0 <= hour < 9.5 or 17.0 <= hour < 19.5:
            return 20.0
        if hour >= 22.0 or hour < 5.0:
            return 32.0
        return self.taxi_speed_kmh

    def taxi_speed_at(self, minute: float, pos: np.ndarray) -> float:
        """Dynamic effective taxi speed.

        This is the supply-side feedback requested in the laboratory:

        * rain -> lower speed;
        * low public-transport availability -> more road congestion;
        * events -> local congestion in the event zone;
        * large train/flight arrivals -> temporary congestion near the hub.

        Since this function is evaluated every simulation step, a taxi already
        in motion can slow down when conditions change.
        """
        speed = self.base_traffic_speed(minute)
        zone_name = self.zone_name_at(pos)

        # Weather can simultaneously increase demand and reduce road speed.
        weather_factor = 1.0 - self.weather_speed_penalty * self.weather_intensity
        speed *= max(weather_factor, 0.40)

        # Poor transit service can shift travellers to cars/taxis and congest roads.
        pt_avail = self.public_transport_availability_at(minute, zone_name)
        pt_factor = 1.0 - self.pt_road_congestion_sensitivity * (1.0 - pt_avail)
        speed *= max(pt_factor, 0.50)

        # Event congestion is localized and phase-dependent.  Arrival traffic
        # builds before the event, relaxes somewhat during it, and is strongest
        # immediately after the event when many people leave at once.
        phase, progress = self.event_phase(minute)
        if zone_name == self.event_zone:
            if phase == "pre":
                # Congestion worsens as event start approaches.
                factor = 1.0 - (1.0 - self.event_pre_speed_factor) * progress
                speed *= factor
            elif phase == "during":
                speed *= self.event_during_speed_factor
            elif phase == "post":
                # Strong initial slowdown that progressively relaxes.
                factor = self.event_speed_factor + (1.0 - self.event_speed_factor) * progress
                speed *= factor

        # Train/flight arrival congestion is temporary and local to the terminal.
        if self.include_hubs:
            for hub in self.hubs.values():
                if minute >= self.hub_congestion_until[hub.hid]:
                    continue
                if self.distance_km(pos, hub.pos) <= self.hub_congestion_radius_km:
                    speed *= self.hub_congestion_speed_factor

        # Numerical/behavioural floor: vehicles never become completely frozen.
        return max(speed, 6.0)

    # ------------------------------ demand model -------------------------

    @staticmethod
    def time_of_day_factor(hour: float) -> float:
        """Non-stationary city-wide demand profile."""
        if 0 <= hour < 5:
            return 0.35
        if 5 <= hour < 7:
            return 0.70
        if 7 <= hour < 10:
            return 1.45
        if 10 <= hour < 16:
            return 0.90
        if 16 <= hour < 20:
            return 1.55
        if 20 <= hour < 23:
            return 1.20
        return 0.75

    def day_factor(self, minute: float) -> float:
        """Day-of-week demand effect, including weekend nightlife."""
        day = self.day_name_at(minute)
        hour = self.clock_hour(minute)

        if day == "Friday" and (hour >= 20 or hour < 2):
            return 1.35
        if day == "Saturday":
            if hour >= 20 or hour < 3:
                return 1.55
            if 7 <= hour < 10:
                return 0.80
            return 1.00
        if day == "Sunday":
            if 7 <= hour < 10:
                return 0.70
            if hour >= 20:
                return 1.10
            return 0.90
        return 1.00

    def zone_rate_per_hour(self, zone: Zone, minute: float) -> float:
        """Ordinary urban taxi demand intensity for a zone.

        Weather, transit availability and events affect passenger demand here.
        Their supply-side effects are handled separately by taxi_speed_at().
        """
        hour = self.clock_hour(minute)
        rate = zone.base_rate_per_hour * self.time_of_day_factor(hour)
        rate *= self.day_factor(minute)
        rate *= self.demand_multiplier

        # More people switch from walking/cycling/transit to taxis in bad weather.
        rate *= 1.0 + self.weather_demand_sensitivity * self.weather_intensity

        # Poor public transport shifts a fraction of latent mobility toward taxis.
        pt_avail = self.public_transport_availability_at(minute, zone.name)
        rate *= 1.0 + self.pt_demand_sensitivity * (1.0 - pt_avail)

        # Event-generated passengers are created explicitly by
        # generate_event_passengers().  During the event itself, ordinary local
        # departures from the venue zone are reduced because many attendees are
        # inside the venue rather than requesting transport.
        phase, _ = self.event_phase(minute)
        if phase == "during" and zone.name == self.event_zone:
            rate *= self.event_during_local_demand_factor

        return rate

    def destination_zone(self, origin_zone: str) -> str:
        """Sample an ordinary destination zone from a simple OD matrix."""
        names = [z.name for z in self.zones]
        probs = {
            "NW": [0.25, 0.30, 0.20, 0.25],
            "NE": [0.30, 0.25, 0.20, 0.25],
            "SW": [0.20, 0.20, 0.30, 0.30],
            "SE": [0.20, 0.25, 0.30, 0.25],
        }[origin_zone]
        return str(self.rng.choice(names, p=probs))

    def choose_destination(self, origin_zone: str) -> Tuple[np.ndarray, str]:
        """Choose a destination, occasionally making a hub the trip destination."""
        if self.include_hubs and self.rng.random() < self.urban_to_hub_probability:
            # Most terminal-bound trips go to the station, a smaller share to airport.
            hub_ids = list(self.hubs.keys())
            weights = np.array(
                [0.65 if self.hubs[hid].kind == "station" else 0.35 for hid in hub_ids],
                dtype=float,
            )
            weights /= weights.sum()
            hid = int(self.rng.choice(hub_ids, p=weights))
            hub = self.hubs[hid]
            return hub.pos.copy(), hub.name

        dz_name = self.destination_zone(origin_zone)
        return self.zone_by_name[dz_name].sample_point(self.rng), dz_name

    def _register_passenger(self, p: Passenger) -> None:
        """Insert passenger and initialize app queue or walking-to-stand state."""
        self.passengers[p.pid] = p
        self.next_pid += 1
        self.total_generated += 1

        if p.source_type == "urban":
            self.urban_generated += 1
        elif p.source_type == "station":
            self.station_generated += 1
        elif p.source_type == "airport":
            self.airport_generated += 1
        elif p.source_type == "event_inbound":
            self.event_inbound_generated += 1
        elif p.source_type == "event_outbound":
            self.event_outbound_generated += 1

        if p.mode == "app":
            self.app_generated += 1
            p.status = "waiting_app"
            self.app_queue.append(p.pid)
        else:
            self.stand_generated += 1
            p.status = "walking"
            sid = self.nearest_stand(p.origin)
            p.stand_id = sid
            walk_dist = float(np.linalg.norm(p.origin - self.stands[sid].pos))
            p.walk_remaining = 60.0 * walk_dist / self.walking_speed_kmh
            if p.walk_remaining <= 1e-9:
                # A person already at the stand does not need a walking step.
                self._arrive_walking_passenger(p, action_time=self.current_time)

    def generate_urban_passengers(self) -> None:
        """Generate ordinary city passengers with a non-homogeneous Poisson process."""
        for zone in self.zones:
            lam = self.zone_rate_per_hour(zone, self.current_time) * self.step_duration / 60.0
            n = int(self.rng.poisson(lam))
            for _ in range(n):
                origin = zone.sample_point(self.rng)
                destination, dz_name = self.choose_destination(zone.name)
                mode = "app" if self.rng.random() < self.p_app else "stand"

                p = Passenger(
                    pid=self.next_pid,
                    origin=origin,
                    destination=destination,
                    origin_zone=zone.name,
                    destination_zone=dz_name,
                    mode=mode,
                    request_time=self.current_time,
                    source_type="urban",
                )
                self._register_passenger(p)

    def generate_event_passengers(self) -> None:
        """Generate directional event mobility with distinct temporal phases.

        Before the event, taxi users originate across the city and travel TO the
        venue.  During the event there is no artificial event burst; ordinary
        local demand is slightly suppressed in ``zone_rate_per_hour``.  After
        the event, passengers originate near the venue and disperse across the
        city with an exponentially decaying intensity.
        """
        if self.event_zone is None or self.event_position is None:
            return

        inbound_rate = self.event_inbound_rate_per_minute(self.current_time)
        outbound_rate = self.event_outbound_rate_per_minute(self.current_time)

        n_in = int(self.rng.poisson(inbound_rate * self.step_duration))
        n_out = int(self.rng.poisson(outbound_rate * self.step_duration))

        # Inbound attendees originate from ordinary city zones.  The event zone
        # is allowed too, but the origin remains a normal spatial point rather
        # than the venue itself.
        zone_names = [z.name for z in self.zones]
        origin_weights = np.array([z.base_rate_per_hour for z in self.zones], dtype=float)
        origin_weights /= origin_weights.sum()

        for _ in range(n_in):
            oz_name = str(self.rng.choice(zone_names, p=origin_weights))
            origin = self.zone_by_name[oz_name].sample_point(self.rng)
            destination = self.event_position + self.rng.normal(0.0, 0.10, size=2)
            destination = np.clip(destination, [0.0, 0.0], [10.0, 10.0])
            mode = "app" if self.rng.random() < self.p_app else "stand"
            p = Passenger(
                pid=self.next_pid,
                origin=origin,
                destination=destination,
                origin_zone=oz_name,
                destination_zone=self.event_zone,
                mode=mode,
                request_time=self.current_time,
                source_type="event_inbound",
                source_name="event",
            )
            self._register_passenger(p)

        # After the event, everyone starts in a compact area around the venue
        # and disperses through the city.  This creates the characteristic sharp
        # queueing pressure immediately after an event finishes.
        dest_weights = np.array([0.25, 0.25, 0.25, 0.25], dtype=float)
        for _ in range(n_out):
            origin = self.event_position + self.rng.normal(0.0, 0.12, size=2)
            origin = np.clip(origin, [0.0, 0.0], [10.0, 10.0])
            dz_name = str(self.rng.choice(zone_names, p=dest_weights))
            destination = self.zone_by_name[dz_name].sample_point(self.rng)
            mode = "app" if self.rng.random() < self.p_app else "stand"
            p = Passenger(
                pid=self.next_pid,
                origin=origin,
                destination=destination,
                origin_zone=self.event_zone,
                destination_zone=dz_name,
                mode=mode,
                request_time=self.current_time,
                source_type="event_outbound",
                source_name="event",
            )
            self._register_passenger(p)

    def expected_event_zone_rate(self, minute: float, horizon_min: float) -> Dict[str, float]:
        """Forecast event-origin demand for rebalancing.

        The rebalancer only needs origin-side demand.  The strong post-event
        burst therefore contributes to the event zone forecast.  A one-minute
        numerical integration is transparent and fast for the short horizons
        used in this laboratory.
        """
        extra = {z.name: 0.0 for z in self.zones}
        if self.event_zone is None or horizon_min <= 0:
            return extra

        steps = max(1, int(math.ceil(horizon_min)))
        expected = 0.0
        for k in range(steps):
            width = min(1.0, horizon_min - k)
            t = minute + k + width / 2.0
            expected += self.event_outbound_rate_per_minute(t) * width
        # Sum of per-minute expected demand over the forecast window converted
        # to an equivalent hourly rate.
        extra[self.event_zone] = expected * 60.0 / horizon_min
        return extra

    def _hub_arrivals_in_step(self, hub: TransportHub) -> List[Tuple[int, int]]:
        """Return (day_index, schedule_index) arrivals falling in this time step."""
        start = self.current_time
        end = self.current_time + self.step_duration
        first_day = int(start // 1440.0)
        last_day = int(end // 1440.0)
        arrivals: List[Tuple[int, int]] = []

        for day_idx in range(first_day, last_day + 1):
            day_start = day_idx * 1440.0
            for schedule_idx, hour in enumerate(hub.arrival_hours):
                arrival_minute = day_start + hour * 60.0
                # Closed-open interval prevents double counting on boundaries.
                if start <= arrival_minute < end:
                    arrivals.append((day_idx, schedule_idx))
        return arrivals

    def generate_hub_passengers(self) -> None:
        """Generate train/flight-arrival taxi demand bursts.

        The burst affects both sides of the taxi system:
          * new passengers arrive almost simultaneously;
          * a short local congestion period reduces taxi speed near the hub.
        """
        if not self.include_hubs:
            return

        zone_names = [z.name for z in self.zones]

        for hub in self.hubs.values():
            for day_idx, schedule_idx in self._hub_arrivals_in_step(hub):
                key = (hub.hid, day_idx, schedule_idx)
                if key in self.processed_hub_arrivals:
                    continue
                self.processed_hub_arrivals.add(key)

                travellers = int(self.rng.poisson(hub.mean_arriving_travellers))
                taxi_users = int(self.rng.binomial(travellers, hub.taxi_share))

                # Arrival traffic, curb activity and queues temporarily slow vehicles.
                if taxi_users > 0:
                    self.hub_congestion_until[hub.hid] = max(
                        self.hub_congestion_until[hub.hid],
                        self.current_time + self.hub_congestion_window_min,
                    )

                probs = np.array([hub.destination_probs[z] for z in zone_names], dtype=float)
                probs /= probs.sum()

                for _ in range(taxi_users):
                    # Small terminal-position jitter gives stand users a short but
                    # non-zero access walk instead of unrealistically spawning on
                    # the exact taxi-stand coordinate.
                    origin = hub.pos + self.rng.normal(0.0, 0.07, size=2)
                    origin = np.clip(origin, [0.0, 0.0], [10.0, 10.0])
                    dz_name = str(self.rng.choice(zone_names, p=probs))
                    destination = self.zone_by_name[dz_name].sample_point(self.rng)
                    mode = "app" if self.rng.random() < hub.p_app else "stand"

                    p = Passenger(
                        pid=self.next_pid,
                        origin=origin,
                        destination=destination,
                        origin_zone=hub.zone_name,
                        destination_zone=dz_name,
                        mode=mode,
                        request_time=self.current_time,
                        source_type=hub.kind,
                        source_name=hub.name,
                    )
                    self._register_passenger(p)

    # ------------------------------ stand logic --------------------------

    def nearest_stand(self, pos: np.ndarray, require_space: bool = False) -> int:
        """Find nearest stand; optionally require one free parking position."""
        candidates = []
        for sid, stand in self.stands.items():
            if require_space and self.idle_taxis_at_stand(sid) >= stand.capacity:
                continue
            candidates.append((self.distance_km(pos, stand.pos), sid))

        if not candidates:
            candidates = [
                (self.distance_km(pos, stand.pos), sid)
                for sid, stand in self.stands.items()
            ]
        return min(candidates)[1]

    def idle_taxis_at_stand(self, sid: int) -> int:
        return sum(
            1 for t in self.taxis.values() if t.state == "idle" and t.stand_id == sid
        )

    def find_idle_taxis(self) -> List[Taxi]:
        return [t for t in self.taxis.values() if t.state == "idle"]

    def closest_idle_taxi(self, pos: np.ndarray) -> Optional[Taxi]:
        idle = self.find_idle_taxis()
        if not idle:
            return None
        return min(idle, key=lambda t: self.distance_km(t.pos, pos))

    # ------------------------------ taxi actions -------------------------

    def send_to_pickup(self, taxi: Taxi, passenger: Passenger) -> None:
        """Dispatch an idle taxi to an app/phone passenger."""
        taxi.stand_id = None

        passenger.status = "assigned"
        passenger.assigned_taxi = taxi.tid
        passenger.assignment_time = self.current_time

        taxi.state = "to_pickup"
        taxi.passenger_id = passenger.pid
        taxi.target_pos = passenger.origin.copy()
        taxi.target_stand_id = None
        if self.distance_km(taxi.pos, passenger.origin) <= 1e-9:
            # Boarding is immediate when taxi and customer are co-located.
            self.start_occupied_trip(taxi, passenger, action_time=self.current_time)

    def start_occupied_trip(
        self, taxi: Taxi, passenger: Passenger, action_time: Optional[float] = None
    ) -> None:
        """Passenger boards and the occupied leg begins."""
        if action_time is None:
            action_time = self.current_time
        passenger.status = "onboard"
        passenger.pickup_time = action_time
        passenger.assigned_taxi = taxi.tid

        taxi.state = "occupied"
        taxi.passenger_id = passenger.pid
        taxi.target_pos = passenger.destination.copy()
        taxi.target_stand_id = None
        taxi.stand_id = None

    def start_return_to_stand(self, taxi: Taxi, action_time: Optional[float] = None) -> None:
        """Return to a stand, immediately if already at a suitable stand."""
        if action_time is None:
            action_time = self.current_time
        taxi.state = "returning"
        taxi.passenger_id = None
        taxi.stand_id = None
        sid = self.nearest_stand(taxi.pos, require_space=True)
        stand = self.stands[sid]
        taxi.target_stand_id = sid
        taxi.target_pos = stand.pos.copy()
        if self.distance_km(taxi.pos, stand.pos) <= 1e-9:
            self.arrive_at_stand(taxi, sid, action_time=action_time)

    def arrive_at_stand(self, taxi: Taxi, sid: int, action_time: float) -> None:
        """Handle an empty taxi reaching a stand."""
        stand = self.stands[sid]
        taxi.pos = stand.pos.copy()
        taxi.target_pos = None
        taxi.target_stand_id = None

        # Stand passengers have priority over parking.
        if stand.passenger_queue:
            pid = stand.passenger_queue.pop(0)
            passenger = self.passengers[pid]
            self.start_occupied_trip(taxi, passenger, action_time=action_time)
            return

        if self.idle_taxis_at_stand(sid) < stand.capacity:
            taxi.state = "idle"
            taxi.stand_id = sid
            taxi.passenger_id = None
            return

        # Stand became full while the taxi was en route; redirect it.
        taxi.stand_id = None
        self.start_return_to_stand(taxi, action_time=action_time)

    # ------------------------------ matching -----------------------------

    def dispatch_app_queue(self) -> None:
        """FIFO passenger queue with closest-idle-taxi dispatching."""
        if not self.app_queue:
            return

        new_queue: List[int] = []
        for pid in self.app_queue:
            passenger = self.passengers[pid]
            if passenger.status != "waiting_app":
                continue

            taxi = self.closest_idle_taxi(passenger.origin)
            if taxi is None:
                new_queue.append(pid)
                continue

            if abs(self.current_time - passenger.request_time) < 1e-9:
                self.immediate_app_dispatches += 1
            self.send_to_pickup(taxi, passenger)

        self.app_queue = new_queue

    def _arrive_walking_passenger(self, p: Passenger, action_time: float) -> None:
        """Record arrival and serve the stand queue in FIFO order if possible."""
        p.walk_remaining = 0.0
        p.stand_arrival_time = action_time
        p.status = "waiting_stand"
        sid = int(p.stand_id)
        stand = self.stands[sid]
        stand.passenger_queue.append(p.pid)
        idle_here = [
            t for t in self.taxis.values()
            if t.state == "idle" and t.stand_id == sid
        ]
        if idle_here:
            waiting = self.passengers[stand.passenger_queue.pop(0)]
            self.start_occupied_trip(idle_here[0], waiting, action_time=action_time)

    def process_walking_passengers(self) -> None:
        """Advance walkers over this interval; record arrivals at its end.

        Positive walking times are rounded up to the next time-step boundary.
        Taxis have already moved over the interval, so a person boarding at its
        end cannot retroactively ride during that same interval.
        """
        action_time = self.current_time + self.step_duration
        for p in self.passengers.values():
            if p.status != "walking":
                continue
            p.walk_remaining -= self.step_duration
            if p.walk_remaining > 1e-9:
                continue
            self._arrive_walking_passenger(p, action_time=action_time)

    # ------------------------------ movement -----------------------------

    def _credit_distance(self, taxi: Taxi, state: str, distance: float) -> None:
        """Accumulate distance under the state in which the movement occurred."""
        if state == "to_pickup":
            taxi.pickup_km += distance
        elif state == "occupied":
            taxi.occupied_km += distance
        elif state == "returning":
            taxi.return_km += distance
        elif state == "rebalancing":
            taxi.rebalance_km += distance

    def _credit_time(self, taxi: Taxi, state: str) -> None:
        """Accumulate fleet time by state."""
        if state == "idle":
            taxi.idle_minutes += self.step_duration
        elif state == "to_pickup":
            taxi.pickup_minutes += self.step_duration
        elif state == "occupied":
            taxi.occupied_minutes += self.step_duration
        elif state == "returning":
            taxi.return_minutes += self.step_duration
        elif state == "rebalancing":
            taxi.rebalance_minutes += self.step_duration

    def advance_taxis(self) -> None:
        """Move every taxi using the current, possibly changing effective speed.

        This distance-based update is what creates the demand/supply feedback:
        when a shock lowers speed, the same physical leg takes more time, so a
        taxi remains unavailable for more simulation steps.
        """
        action_time = self.current_time + self.step_duration

        for taxi in self.taxis.values():
            state_at_start = taxi.state
            self._credit_time(taxi, state_at_start)

            if state_at_start == "idle":
                continue
            if taxi.target_pos is None:
                raise RuntimeError(f"Taxi {taxi.tid} in state {taxi.state} has no target")

            euclid_remaining = float(np.linalg.norm(taxi.target_pos - taxi.pos))
            road_remaining = euclid_remaining * self.road_distance_factor

            # Already effectively at destination (can occur from numerical rounding).
            if road_remaining <= 1e-10:
                moved_road = 0.0
                arrived = True
            else:
                speed = self.taxi_speed_at(self.current_time, taxi.pos)
                max_road_move = speed * self.step_duration / 60.0
                moved_road = min(max_road_move, road_remaining)
                arrived = moved_road >= road_remaining - 1e-10

                if arrived:
                    taxi.pos = taxi.target_pos.copy()
                else:
                    euclid_move = moved_road / self.road_distance_factor
                    direction = (taxi.target_pos - taxi.pos) / euclid_remaining
                    taxi.pos = taxi.pos + direction * euclid_move

            self._credit_distance(taxi, state_at_start, moved_road)

            if not arrived:
                continue

            # Process the state transition at the end of this time step.
            if state_at_start == "to_pickup":
                p = self.passengers[int(taxi.passenger_id)]
                self.start_occupied_trip(taxi, p, action_time=action_time)

            elif state_at_start == "occupied":
                p = self.passengers[int(taxi.passenger_id)]
                p.status = "completed"
                p.dropoff_time = action_time
                taxi.passenger_id = None
                self.start_return_to_stand(taxi, action_time=action_time)

            elif state_at_start in {"returning", "rebalancing"}:
                sid = int(taxi.target_stand_id)
                self.arrive_at_stand(taxi, sid, action_time=action_time)

    # ------------------------------ rebalancing --------------------------

    def expected_hub_zone_rate(self, minute: float, horizon_min: float) -> Dict[str, float]:
        """Convert scheduled hub arrivals in a forecast window to equivalent rates.

        This lets the simple rebalancer anticipate a near-future train/flight
        arrival rather than reacting only after its passengers are already queued.
        """
        extra = {z.name: 0.0 for z in self.zones}
        if not self.include_hubs or horizon_min <= 0:
            return extra

        start = minute
        end = minute + horizon_min
        first_day = int(start // 1440.0)
        last_day = int(end // 1440.0)

        for hub in self.hubs.values():
            expected_requests = 0.0
            for day_idx in range(first_day, last_day + 1):
                day_start = day_idx * 1440.0
                for hour in hub.arrival_hours:
                    arr = day_start + hour * 60.0
                    if start <= arr < end:
                        expected_requests += hub.mean_arriving_travellers * hub.taxi_share
            extra[hub.zone_name] += expected_requests * 60.0 / horizon_min
        return extra

    def rebalance_fleet(self) -> None:
        """Relocate some idle taxis toward zones with larger forecast demand."""
        if not self.rebalancing or self.current_time <= 0:
            return
        if (self.current_time % self.rebalance_interval_min) >= self.dt:
            return

        idle = self.find_idle_taxis()
        if len(idle) < 2:
            return

        horizon = float(self.rebalance_interval_min)
        hub_extra = self.expected_hub_zone_rate(self.current_time, horizon_min=horizon)
        event_extra = self.expected_event_zone_rate(self.current_time, horizon_min=horizon)
        zone_rates = {
            z.name: (
                self.zone_rate_per_hour(z, self.current_time)
                + hub_extra[z.name]
                + event_extra[z.name]
            )
            for z in self.zones
        }
        total_rate = sum(zone_rates.values())
        if total_rate <= 0:
            return

        zone_idle = {z.name: 0 for z in self.zones}
        for taxi in idle:
            if taxi.stand_id is not None:
                zone_idle[self.stands[taxi.stand_id].zone_name] += 1

        desired = {
            z.name: int(round(len(idle) * zone_rates[z.name] / total_rate))
            for z in self.zones
        }

        deficits: List[str] = []
        surpluses: List[str] = []
        for z in self.zones:
            diff = desired[z.name] - zone_idle[z.name]
            if diff > 0:
                deficits.extend([z.name] * diff)
            elif diff < 0:
                surpluses.extend([z.name] * (-diff))

        # Respect the requested fraction, including zero and small fleets.
        max_moves = int(math.floor(len(idle) * self.rebalance_fraction))
        moves = min(len(deficits), len(surpluses), max_moves)
        if moves <= 0:
            return

        for _ in range(moves):
            deficit_zone = deficits.pop(0)
            surplus_zone = surpluses.pop(0)

            candidates = [
                t for t in self.find_idle_taxis()
                if t.stand_id is not None
                and self.stands[t.stand_id].zone_name == surplus_zone
            ]
            if not candidates:
                continue

            target_stands = [s for s in self.stands.values() if s.zone_name == deficit_zone]
            taxi = min(
                candidates,
                key=lambda t: min(self.distance_km(t.pos, s.pos) for s in target_stands),
            )
            stand = min(target_stands, key=lambda s: self.distance_km(taxi.pos, s.pos))

            taxi.stand_id = None
            taxi.state = "rebalancing"
            taxi.target_stand_id = stand.sid
            taxi.target_pos = stand.pos.copy()

    # ------------------------------ simulation ---------------------------

    def step(self) -> None:
        """Generate and dispatch at t, then evolve to t + step_duration.

        All decisions use the state at the start of the interval. Movement and
        positive walking completions are recorded at its end. A taxi becoming
        idle at the end can be dispatched at the next boundary, never at t.
        Arrivals within an interval are approximated by its start boundary.
        """
        interval = self.step_duration
        if interval <= 0:
            return
        self.generate_urban_passengers()
        self.generate_event_passengers()
        self.generate_hub_passengers()
        self.dispatch_app_queue()
        self.rebalance_fleet()

        self.advance_taxis()
        self.process_walking_passengers()
        self.current_time = min(self.duration_minutes, self.current_time + interval)

    def run(self) -> Dict[str, float]:
        """Run to the requested horizon and return performance indicators."""
        while self.current_time < self.duration_minutes:
            self.step()
        return self.metrics()

    # ------------------------------ metrics ------------------------------

    def metrics(self) -> Dict[str, float]:
        """Compute KPIs at the current observation time.

        Waiting/access means use every passenger who has boarded, including
        those still travelling. Walking means use everyone who reached a stand.
        Neither is an unconditional final mean when people are still waiting.
        Lower-bound means also include the time already spent by people whose
        wait/walk is not finished; their final times remain unknown. Counts make
        these populations explicit rather than silently omitting the backlog.
        """
        passengers = list(self.passengers.values())
        completed = [p for p in passengers if p.status == "completed"]
        boarded = [p for p in passengers if p.pickup_time is not None]
        app_passengers = [p for p in passengers if p.mode == "app"]
        stand_passengers = [p for p in passengers if p.mode == "stand"]
        app_boarded = [p for p in app_passengers if p.pickup_time is not None]
        stand_boarded = [p for p in stand_passengers if p.pickup_time is not None]
        stand_arrived = [p for p in stand_passengers if p.stand_arrival_time is not None]

        def safe_mean(values: List[float]) -> float:
            return float(np.mean(values)) if values else float("nan")

        app_wait = [p.pickup_time - p.request_time for p in app_boarded]
        stand_walk = [p.stand_arrival_time - p.request_time for p in stand_arrived]
        stand_wait = [p.pickup_time - p.stand_arrival_time for p in stand_boarded]
        total_access = [p.pickup_time - p.request_time for p in boarded]

        def observed_access(p: Passenger) -> float:
            end = p.pickup_time if p.pickup_time is not None else self.current_time
            return end - p.request_time

        app_wait_lower_bound = [observed_access(p) for p in app_passengers]
        access_lower_bound = [observed_access(p) for p in passengers]
        walk_lower_bound = [
            (p.stand_arrival_time if p.stand_arrival_time is not None else self.current_time)
            - p.request_time
            for p in stand_passengers
        ]
        # This particular lower bound is for the cohort that reached a stand;
        # passengers still walking have not yet entered a stand queue.
        stand_wait_lower_bound = [
            (p.pickup_time if p.pickup_time is not None else self.current_time)
            - p.stand_arrival_time
            for p in stand_arrived
        ]

        source_access: Dict[str, List[float]] = {
            "urban": [], "station": [], "airport": [],
            "event_inbound": [], "event_outbound": [],
        }
        for p in boarded:
            if p.source_type in source_access:
                source_access[p.source_type].append(p.pickup_time - p.request_time)

        # Use elapsed observation time, so intermediate metrics also reconcile.
        total_minutes = self.fleet_size * self.current_time
        occupied_minutes = sum(t.occupied_minutes for t in self.taxis.values())
        idle_minutes = sum(t.idle_minutes for t in self.taxis.values())
        empty_minutes = sum(
            t.pickup_minutes + t.return_minutes + t.rebalance_minutes
            for t in self.taxis.values()
        )

        occupied_km = sum(t.occupied_km for t in self.taxis.values())
        empty_km = sum(
            t.pickup_km + t.return_km + t.rebalance_km for t in self.taxis.values()
        )
        total_km = occupied_km + empty_km

        not_boarded_app = len(app_passengers) - len(app_boarded)
        not_boarded_stand = len(stand_passengers) - len(stand_boarded)
        onboard = sum(p.status == "onboard" for p in passengers)

        return {
            "generated": float(self.total_generated),
            "app_generated": float(self.app_generated),
            "stand_generated": float(self.stand_generated),
            "urban_generated": float(self.urban_generated),
            "station_generated": float(self.station_generated),
            "airport_generated": float(self.airport_generated),
            "event_inbound_generated": float(self.event_inbound_generated),
            "event_outbound_generated": float(self.event_outbound_generated),
            "event_generated": float(
                self.event_inbound_generated + self.event_outbound_generated
            ),
            "completed": float(len(completed)),
            "boarded": float(len(boarded)),
            "boarded_app": float(len(app_boarded)),
            "boarded_stand": float(len(stand_boarded)),
            "arrived_at_stand": float(len(stand_arrived)),
            "completion_rate": len(completed) / self.total_generated
            if self.total_generated else float("nan"),
            "avg_app_wait_min": safe_mean(app_wait),
            "avg_stand_walk_min": safe_mean(stand_walk),
            "avg_stand_wait_min": safe_mean(stand_wait),
            "avg_total_access_min": safe_mean(total_access),
            "avg_app_wait_lower_bound_min": safe_mean(app_wait_lower_bound),
            "avg_stand_walk_lower_bound_min": safe_mean(walk_lower_bound),
            "avg_stand_wait_lower_bound_min": safe_mean(stand_wait_lower_bound),
            "avg_total_access_lower_bound_min": safe_mean(access_lower_bound),
            "avg_urban_access_min": safe_mean(source_access["urban"]),
            "avg_station_access_min": safe_mean(source_access["station"]),
            "avg_airport_access_min": safe_mean(source_access["airport"]),
            "avg_event_inbound_access_min": safe_mean(source_access["event_inbound"]),
            "avg_event_outbound_access_min": safe_mean(source_access["event_outbound"]),
            "availability_idle_share": idle_minutes / total_minutes
            if total_minutes else float("nan"),
            "utilization_occupied_share": occupied_minutes / total_minutes
            if total_minutes else float("nan"),
            "empty_running_share": empty_minutes / total_minutes
            if total_minutes else float("nan"),
            "immediate_app_dispatch_rate": self.immediate_app_dispatches / self.app_generated
            if self.app_generated else float("nan"),
            "occupied_km": occupied_km,
            "empty_km": empty_km,
            "empty_distance_share": empty_km / total_km if total_km > 0 else float("nan"),
            "not_boarded_app": float(not_boarded_app),
            "not_boarded_stand": float(not_boarded_stand),
            "walking_to_stand": float(sum(p.status == "walking" for p in passengers)),
            "waiting_at_stand": float(sum(p.status == "waiting_stand" for p in passengers)),
            "onboard": float(onboard),
            # Unfinished trips include customers already aboard at the horizon.
            "unfinished_app": float(sum(p.status != "completed" for p in app_passengers)),
            "unfinished_stand": float(sum(p.status != "completed" for p in stand_passengers)),
        }


